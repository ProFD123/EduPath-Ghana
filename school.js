window.findSchool = function(name) {

    if (!name) return null;

    return window.schools.find(school =>
        school.name
            .toLowerCase()
            .includes(
                name.toLowerCase()
            )
    );

};


// -------------------------------------------------
// 7. FIND SCHOOLS BY PROGRAMME
// -------------------------------------------------

window.findSchoolsByProgramme =
    function(programme) {

        if (!programme) return [];

        return window.schools.filter(
            school =>
                school.programmes.some(
                    item =>
                        item.toLowerCase()
                        === programme.toLowerCase()
                )
        );

    };


